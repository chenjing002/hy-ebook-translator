/* hy-ebook-translator — shared front-end for the library and the reader.
   Everything is static: `library.json` is generated by `hy site`, and each
   document is fetched as the same Markdown file that lives in `outputs/`. */

const STORE = {
  get(key, fallback) {
    try { const v = localStorage.getItem(key); return v === null ? fallback : v; }
    catch { return fallback; }
  },
  set(key, value) { try { localStorage.setItem(key, value); } catch { /* private mode */ } },
};

/* ── theme ──────────────────────────────────────────────────────────────── */

function initTheme() {
  const saved = STORE.get('theme', '');
  if (saved) document.documentElement.dataset.theme = saved;
  const btn = document.getElementById('theme-btn');
  if (!btn) return;
  const paint = () => {
    const explicit = document.documentElement.dataset.theme;
    const dark = explicit === 'dark' ||
      (!explicit && matchMedia('(prefers-color-scheme: dark)').matches);
    btn.textContent = dark ? '☾' : '☀';
    btn.setAttribute('aria-label', dark ? 'Switch to light theme' : 'Switch to dark theme');
  };
  btn.addEventListener('click', () => {
    const explicit = document.documentElement.dataset.theme;
    const dark = explicit === 'dark' ||
      (!explicit && matchMedia('(prefers-color-scheme: dark)').matches);
    const next = dark ? 'light' : 'dark';
    document.documentElement.dataset.theme = next;
    STORE.set('theme', next);
    paint();
  });
  paint();
}

/* ── library ────────────────────────────────────────────────────────────── */

async function initLibrary() {
  const shelf = document.getElementById('shelf');
  const search = document.getElementById('search');
  const count = document.getElementById('count');
  let docs = [];
  try {
    const res = await fetch('library.json', { cache: 'no-cache' });
    if (!res.ok) throw new Error(res.status);
    docs = (await res.json()).documents || [];
  } catch {
    shelf.innerHTML = '<p class="empty">Could not load <code>library.json</code>. ' +
      'Run <code>./hy site</code> to generate it.</p>';
    return;
  }
  if (!docs.length) {
    shelf.innerHTML = '<p class="empty">The shelf is empty.<br>' +
      'Drop English Markdown into <code>inputs/</code> and run <code>./hy run</code>.</p>';
    if (count) count.textContent = '';
    return;
  }

  const render = (list) => {
    if (!list.length) {
      shelf.innerHTML = '<p class="empty">Nothing matches that search.</p>';
      return;
    }
    shelf.innerHTML = '';
    for (const doc of list) {
      const card = document.createElement('a');
      card.className = 'card';
      card.href = `reader.html?doc=${encodeURIComponent(doc.file)}`;
      const title = document.createElement('h2');
      title.textContent = doc.title_zh || doc.title;
      card.appendChild(title);
      if (doc.title && doc.title_zh && doc.title !== doc.title_zh) {
        const en = document.createElement('p');
        en.className = 'en';
        en.textContent = doc.title;
        card.appendChild(en);
      }
      const meta = document.createElement('div');
      meta.className = 'meta';
      for (const text of [
        `${doc.sections} 节`,
        `${fmt(doc.cjk_chars)} 汉字`,
        `${doc.minutes} min read`,
        doc.updated,
      ]) {
        if (!text) continue;
        const span = document.createElement('span');
        span.textContent = text;
        meta.appendChild(span);
      }
      card.appendChild(meta);
      shelf.appendChild(card);
    }
  };

  if (count) count.textContent = `${docs.length} 篇文档`;
  render(docs);

  if (search) {
    search.addEventListener('input', () => {
      const q = search.value.trim().toLowerCase();
      render(!q ? docs : docs.filter((d) =>
        [d.title, d.title_zh, d.file, d.excerpt].some((f) => (f || '').toLowerCase().includes(q))));
    });
  }
}

const fmt = (n) => (n || 0).toLocaleString('en-US');

/* ── reader ─────────────────────────────────────────────────────────────── */

async function initReader() {
  const article = document.getElementById('content');
  const params = new URLSearchParams(location.search);
  const file = params.get('doc');
  if (!file || /(^|[\\/])\.\.($|[\\/])/.test(file)) {
    article.innerHTML = '<p class="empty">No document requested. ' +
      '<a href="index.html">Back to the library</a>.</p>';
    return;
  }

  let markdown;
  try {
    const res = await fetch(`outputs/${encodePath(file)}`, { cache: 'no-cache' });
    if (!res.ok) throw new Error(res.status);
    markdown = await res.text();
  } catch {
    article.innerHTML = `<p class="empty">Could not load <code>outputs/${escapeHtml(file)}</code>.</p>`;
    return;
  }

  marked.setOptions({ gfm: true, breaks: false, headerIds: true, mangle: false });
  const math = extractMath(stripProvenance(markdown));
  const rendered = document.createElement('template');
  rendered.innerHTML = marked.parse(math.text);
  // Converted ebooks can contain expired image URLs. Keep the Markdown file
  // intact, but omit images from the reading page before inserting the DOM.
  for (const img of rendered.content.querySelectorAll('img')) {
    const parent = img.parentElement;
    img.remove();
    if (parent?.tagName === 'P' && !parent.textContent.trim() && !parent.children.length) {
      parent.remove();
    }
  }
  article.replaceChildren(rendered.content);

  tagOriginals(article);
  renderMath(article, math.spans);
  highlight(article);
  const title = buildTitle(article, file);
  buildToc(article);
  initLangToggle();
  initFontScale();
  initProgress();
  document.title = `${title} · 双语书架`;
}

/* The generated file opens with an HTML provenance comment; it is useful in the
   repository but not on the page. */
function stripProvenance(md) {
  return md.replace(/^<!--\s*Generated by hy-ebook-translator[\s\S]*?-->\s*/, '');
}

/* Every original-language block is preceded by an invisible <!--en--> comment.
   Promote the block that follows into `.src` so CSS can style and toggle it. */
function tagOriginals(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_COMMENT);
  const marks = [];
  while (walker.nextNode()) {
    if (walker.currentNode.data.trim() === 'en') marks.push(walker.currentNode);
  }
  for (const mark of marks) {
    let node = mark.nextSibling;
    while (node && node.nodeType !== Node.ELEMENT_NODE) node = node.nextSibling;
    mark.remove();
    if (!node) continue;
    const heading = node.previousElementSibling;
    if (heading && /^H[1-6]$/.test(heading.tagName)) {
      foldHeading(heading, node);
    } else {
      node.classList.add('src');
      if (heading) heading.classList.add('tr');
    }
  }
}

/* Move both languages inside the heading element itself: a single heading keeps
   the document outline clean, and each language can be shown on its own. */
function foldHeading(heading, echo) {
  const zh = document.createElement('span');
  zh.className = 'h-zh';
  while (heading.firstChild) zh.appendChild(heading.firstChild);
  const en = document.createElement('span');
  en.className = 'h-en';
  while (echo.firstChild) en.appendChild(echo.firstChild);
  heading.append(zh, en);
  echo.remove();
}

/* ── math ────────────────────────────────────────────────────────────────── */

/* Math is lifted out of the Markdown *before* it is parsed, and rendered back
   into the DOM afterwards. Two reasons, both of which bite on these documents:

   * KaTeX's auto-render treats every `$` as a possible delimiter. In a book
     about financial statements that is a disaster: "improperly accounted for
     $68.5 million ... Standard & Poor's" would render the prose between two
     amounts as algebra. `mathSpans` applies the same rule as
     `hymt/protect.py` — a single-dollar span may not be padded with spaces
     unless what it holds is unmistakably TeX, and it is neither long nor full
     of markup — so the reader and the translator agree on what counts as math.
   * Markdown owns the same punctuation TeX does. Left in place, `\$` loses its
     backslash, `&` becomes `&amp;`, and `$a_i$ … $b_i$` has its subscripts
     eaten as emphasis — all before KaTeX ever sees them. */

const MATH_SKIP = new Set(['CODE', 'PRE', 'SCRIPT', 'STYLE', 'TEXTAREA', 'OPTION']);
const TEXISH = /[\\^_{}]/;
/* Inline math is short and holds no markup. Without these two limits, two
   currency amounts far apart on one line of a converted table would pair up
   and swallow everything between them. */
const MATH_INLINE_MAX = 200;
/* Private-use characters: Markdown has no meaning for them, so a placeholder
   survives parsing intact and stays findable in the rendered DOM. */
const MATH_OPEN = '';
const MATH_CLOSE = '';
const MATH_TOKEN_RE = /(\d+)/g;

/* The `$` that closes an inline span, or -1. `\$` is an escaped dollar inside
   TeX and must not end the span — the book writes `$\frac{\$24}{X}$`. */
function closingDollar(text, from) {
  for (let k = from; k < text.length; k += 1) {
    if (text[k] === '\\') { k += 1; continue; }
    if (text[k] === '\n') return -1;
    if (text[k] === '$') return k;
  }
  return -1;
}

function mathSpans(text) {
  const spans = [];
  const isWord = (ch) => ch !== undefined && /[\w$]/.test(ch);
  let i = 0;
  let fenced = false;
  while (i < text.length) {
    // Code is never math: skip whole fenced blocks and inline backtick spans.
    if (i === 0 || text[i - 1] === '\n') {
      const fence = /^ {0,3}(`{3,}|~{3,})/.exec(text.slice(i, i + 80));
      if (fence) fenced = !fenced;
      if (fenced) {
        const nl = text.indexOf('\n', i);
        i = nl === -1 ? text.length : nl + 1;
        continue;
      }
    }
    const ch = text[i];
    if (ch === '`') {
      const run = /^`+/.exec(text.slice(i))[0];
      const close = text.indexOf(run, i + run.length);
      i = close === -1 ? i + run.length : close + run.length;
      continue;
    }
    if (ch === '\\' && (text[i + 1] === '[' || text[i + 1] === '(')) {
      const close = text[i + 1] === '[' ? '\\]' : '\\)';
      const end = text.indexOf(close, i + 2);
      if (end !== -1) {
        spans.push({ start: i, end: end + 2, tex: text.slice(i + 2, end), display: close === '\\]' });
        i = end + 2;
        continue;
      }
      i += 2;
      continue;
    }
    if (ch === '$' && text[i + 1] === '$') {
      const end = text.indexOf('$$', i + 2);
      if (end !== -1) {
        spans.push({ start: i, end: end + 2, tex: text.slice(i + 2, end), display: true });
        i = end + 2;
        continue;
      }
      i += 2;
      continue;
    }
    if (ch === '$' && !isWord(text[i - 1])) {
      const end = closingDollar(text, i + 1);
      const body = end === -1 ? '' : text.slice(i + 1, end);
      const padded = body !== body.trim();
      if (end !== -1 && body.trim() && !isWord(text[end + 1])
          && body.length <= MATH_INLINE_MAX && !/[<>`]/.test(body)
          && (!padded || TEXISH.test(body))) {
        spans.push({ start: i, end: end + 1, tex: body.trim(), display: false });
        i = end + 1;
        continue;
      }
    }
    i += 1;
  }
  return spans;
}

/* Replace every math span with a placeholder, returning the Markdown to parse
   and the TeX to render back into it. */
function extractMath(md) {
  const found = mathSpans(md);
  if (!found.length) return { text: md, spans: [] };
  const out = [];
  const spans = [];
  let pos = 0;
  for (const span of found) {
    out.push(md.slice(pos, span.start), `${MATH_OPEN}${spans.length}${MATH_CLOSE}`);
    spans.push(span);
    pos = span.end;
  }
  out.push(md.slice(pos));
  return { text: out.join(''), spans };
}

function renderMath(root, spans) {
  if (!spans.length) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      if (!node.data.includes(MATH_OPEN)) return NodeFilter.FILTER_REJECT;
      for (let el = node.parentElement; el && el !== root; el = el.parentElement) {
        if (MATH_SKIP.has(el.tagName)) return NodeFilter.FILTER_REJECT;
      }
      return NodeFilter.FILTER_ACCEPT;
    },
  });
  const targets = [];
  while (walker.nextNode()) targets.push(walker.currentNode);

  for (const node of targets) {
    const frag = document.createDocumentFragment();
    let pos = 0;
    MATH_TOKEN_RE.lastIndex = 0;
    for (let m = MATH_TOKEN_RE.exec(node.data); m; m = MATH_TOKEN_RE.exec(node.data)) {
      if (m.index > pos) frag.append(node.data.slice(pos, m.index));
      const span = spans[Number(m[1])];
      pos = m.index + m[0].length;
      if (!span) continue;
      const host = document.createElement(span.display ? 'div' : 'span');
      if (typeof katex === 'undefined') {
        frag.append(span.display ? `$$${span.tex}$$` : `$${span.tex}$`);
        continue;
      }
      try {
        katex.render(span.tex, host, { displayMode: span.display, throwOnError: true });
        frag.append(host);
      } catch {
        // Not valid TeX after all: show it as the author wrote it.
        frag.append(span.display ? `$$${span.tex}$$` : `$${span.tex}$`);
      }
    }
    if (pos < node.data.length) frag.append(node.data.slice(pos));
    node.replaceWith(frag);
  }
}

function highlight(root) {
  if (typeof hljs === 'undefined') return;
  for (const block of root.querySelectorAll('pre code')) {
    try { hljs.highlightElement(block); } catch { /* unknown language */ }
  }
}

function buildTitle(article, file) {
  const host = document.getElementById('doc-title');
  const first = article.querySelector('h1');
  let title = file.replace(/\.md$/i, '');
  if (first) {
    title = ((first.querySelector('.h-zh') || first).textContent || '').trim();
    const holder = document.getElementById('reader-title');
    if (holder) {
      holder.querySelector('h1').replaceWith(first);
      holder.hidden = false;
    }
  }
  if (host) host.textContent = title;
  return title;
}

function buildToc(article) {
  const toc = document.getElementById('toc');
  if (!toc) return;
  const headings = [...article.querySelectorAll('h1, h2, h3, h4')];
  if (headings.length < 2) {
    toc.remove();
    const btn = document.getElementById('toc-btn');
    if (btn) btn.remove();
    return;
  }
  const list = document.createElement('ol');
  headings.forEach((h, i) => {
    if (!h.id) h.id = `sec-${i}`;
    const li = document.createElement('li');
    li.className = `lvl-${h.tagName[1]}`;
    const a = document.createElement('a');
    a.href = `#${h.id}`;
    a.textContent = ((h.querySelector('.h-zh') || h).textContent || '').trim();
    li.appendChild(a);
    list.appendChild(li);
  });
  toc.appendChild(list);

  const btn = document.getElementById('toc-btn');
  const scrim = document.getElementById('scrim');
  const setOpen = (open) => {
    toc.dataset.open = String(open);
    if (scrim) scrim.dataset.open = String(open);
  };
  if (btn) btn.addEventListener('click', () => setOpen(toc.dataset.open !== 'true'));
  if (scrim) scrim.addEventListener('click', () => setOpen(false));
  toc.addEventListener('click', (e) => { if (e.target.tagName === 'A') setOpen(false); });

  const links = [...toc.querySelectorAll('a')];
  const spy = new IntersectionObserver((entries) => {
    for (const entry of entries) {
      if (!entry.isIntersecting) continue;
      links.forEach((a) => a.classList.toggle('active', a.hash === `#${entry.target.id}`));
    }
  }, { rootMargin: '-70px 0px -70% 0px' });
  headings.forEach((h) => spy.observe(h));
}

function initLangToggle() {
  const group = document.getElementById('lang');
  if (!group) return;
  const apply = (mode) => {
    document.body.dataset.lang = mode;
    STORE.set('lang', mode);
    for (const b of group.querySelectorAll('button')) {
      b.setAttribute('aria-pressed', String(b.dataset.lang === mode));
    }
  };
  group.addEventListener('click', (e) => {
    const btn = e.target.closest('button');
    if (btn) apply(btn.dataset.lang);
  });
  apply(STORE.get('lang', 'both'));
}

function initFontScale() {
  const group = document.getElementById('scale');
  if (!group) return;
  const apply = (value) => {
    document.documentElement.style.setProperty('--reader-scale', value);
    STORE.set('scale', value);
  };
  group.addEventListener('click', (e) => {
    const btn = e.target.closest('button');
    if (!btn) return;
    const current = parseFloat(STORE.get('scale', '1'));
    const next = Math.min(1.5, Math.max(0.85, current + (btn.dataset.step === 'up' ? 0.08 : -0.08)));
    apply(next.toFixed(2));
  });
  apply(STORE.get('scale', '1'));
}

function initProgress() {
  const bar = document.getElementById('progress');
  if (!bar) return;
  const update = () => {
    const max = document.documentElement.scrollHeight - innerHeight;
    bar.style.width = `${max > 0 ? Math.min(100, (scrollY / max) * 100) : 0}%`;
  };
  addEventListener('scroll', update, { passive: true });
  addEventListener('resize', update);
  update();
}

/* A document name may hold spaces, an apostrophe or Chinese characters; the
   query string is already decoded by URLSearchParams, so the path has to be
   encoded again before it can be fetched. */
function encodePath(path) {
  return path.split('/').map(encodeURIComponent).join('/');
}

function escapeHtml(text) {
  const div = document.createElement('div');
  div.textContent = text;
  return div.innerHTML;
}

document.addEventListener('DOMContentLoaded', () => {
  initTheme();
  if (document.getElementById('shelf')) initLibrary();
  if (document.getElementById('content')) initReader();
});
