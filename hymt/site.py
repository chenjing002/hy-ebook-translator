"""Static reading site.

`index.html`, `reader.html` and `assets/` are ordinary checked-in files, so the
site can be edited by hand. This module only derives `library.json` — the shelf
manifest — from whatever currently sits in `outputs/`, and drops the
`.nojekyll` marker GitHub Pages needs to serve an `assets/` directory as-is.
"""

from __future__ import annotations

import json
import re
import time
from pathlib import Path

from .config import Config

CJK_RE = re.compile(r"[㐀-䶿一-鿿]")
H1_RE = re.compile(r"^#\s+(.+?)\s*$", re.MULTILINE)
HEADING_RE = re.compile(r"^(#{1,6})\s+\S", re.MULTILINE)
PROVENANCE_RE = re.compile(r"\A<!--\s*Generated by hy-ebook-translator.*?-->\s*", re.DOTALL)
WORD_RE = re.compile(r"[A-Za-z][A-Za-z'’-]*")

# Reading speeds used for the estimate on each card.
CJK_PER_MIN = 400
WORDS_PER_MIN = 220


def describe(path: Path) -> dict:
    text = PROVENANCE_RE.sub("", path.read_text(encoding="utf-8"))
    title_zh = ""
    title_en = ""
    m = H1_RE.search(text)
    if m:
        title_zh = _plain(m.group(1))
        title_en = _echo_after(text, m.end())

    cjk = len(CJK_RE.findall(text))
    words = len(WORD_RE.findall(text))
    minutes = max(1, round(cjk / CJK_PER_MIN + words / WORDS_PER_MIN))
    sections = max(0, len(HEADING_RE.findall(text)) - (1 if m else 0))

    return {
        "file": path.name,
        "title": title_en or title_zh or path.stem,
        "title_zh": title_zh or path.stem,
        "excerpt": _excerpt(text),
        "cjk_chars": cjk,
        "words": words,
        "sections": sections,
        "minutes": minutes,
        "bytes": path.stat().st_size,
        "updated": time.strftime("%Y-%m-%d", time.localtime(path.stat().st_mtime)),
        "updated_ts": int(path.stat().st_mtime),
    }


def build_library(cfg: Config) -> dict:
    docs = [describe(p) for p in sorted(cfg.outputs_dir.glob("*.md"))]
    docs.sort(key=lambda d: -d["updated_ts"])
    return {
        "generated": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "title": cfg.publish.site_title,
        "subtitle": cfg.publish.site_subtitle,
        "model": cfg.model.repo,
        "direction": f"{cfg.translate.source_lang} → {cfg.translate.target_lang}",
        "documents": docs,
    }


def write_site(cfg: Config) -> list[Path]:
    """Refresh the generated parts of the site. Returns the files touched."""
    written: list[Path] = []
    manifest = cfg.root / "library.json"
    manifest.write_text(
        json.dumps(build_library(cfg), ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    written.append(manifest)

    # GitHub Pages runs Jekyll by default, which would skip our asset folder.
    nojekyll = cfg.root / ".nojekyll"
    if not nojekyll.exists():
        nojekyll.write_text("")
        written.append(nojekyll)
    return written


def _plain(text: str) -> str:
    """Strip inline Markdown so a title can go straight into the DOM."""
    text = re.sub(r"`([^`]*)`", r"\1", text)
    text = re.sub(r"\*\*([^*]*)\*\*", r"\1", text)
    text = re.sub(r"[*_]([^*_]*)[*_]", r"\1", text)
    text = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", text)
    return text.strip()


def _echo_after(text: str, pos: int) -> str:
    """The original-language title that follows the translated H1."""
    tail = text[pos:pos + 600].lstrip("\n")
    lines = [ln.strip() for ln in tail.split("\n")]
    for line in lines:
        if not line or line == "<!--en-->":
            continue
        if line.startswith("#"):
            return ""
        return _plain(line)
    return ""


def _excerpt(text: str, limit: int = 120) -> str:
    body = H1_RE.sub("", text, count=1)
    for raw in body.split("\n\n"):
        line = raw.strip()
        if not line or line.startswith(("#", "<!--", "|", "```", "$$", ">", "-", "*", "[")):
            continue
        if not CJK_RE.search(line):
            continue
        plain = _plain(line)
        return plain[:limit] + ("…" if len(plain) > limit else "")
    return ""
