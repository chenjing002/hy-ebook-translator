"""Bilingual Markdown assembly.

The output interleaves the two languages block by block: the Chinese
translation first, then the original English. Three rules keep the result
readable rather than merely complete:

* Blocks with no prose — code fences, display math, non-table HTML, rules, link
  definitions — are emitted once, verbatim. HTML table cells are translated
  while their tags and attributes stay in place.
* The English side of a prose block is reproduced from the *original source
  text*, not re-generated, so soft wraps, emphasis and spacing survive exactly.
* Each original-language block is preceded by an invisible ``<!--en-->``
  comment. Markdown renderers ignore it; the reading site uses it to style
  translation and original differently, and to offer a language toggle.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from .config import Config
from .mdparse import Block

MARKER = "<!--en-->"
CJK_RE = re.compile(r"[㐀-䶿一-鿿]")
# Heading text that can safely be wrapped in italics.
PLAIN_RE = re.compile(r"^[^*_`$\[\]<>]+$")


@dataclass
class Assembled:
    text: str
    pairs: int
    passthrough: int


def assemble(blocks: list[Block], zh: dict[str, str], cfg: Config,
             header: str | None = None) -> Assembled:
    lookup = lambda uid: zh.get(uid, "")  # noqa: E731
    out: list[str] = []
    pairs = passthrough = 0
    zh_first = cfg.layout.order != "en-first"
    marker = MARKER if cfg.layout.markers else ""

    for block in blocks:
        if block.kind == "front_matter":
            out.append(block.raw)
            passthrough += 1
            continue

        units = list(block.iter_units())
        translatable = [u for u in units if u.translatable()]
        if not translatable:
            out.append(block.raw)
            passthrough += 1
            continue

        target = block.render_target(lookup).strip()
        source = block.raw.strip()

        # The translator echoed the source (names, formulae, acronyms): show it once.
        if _same(target, source) or not CJK_RE.search(target):
            out.append(source)
            passthrough += 1
            continue

        if block.kind == "heading":
            out.extend(_heading_pair(block, target, cfg, marker, zh_first))
        elif block.kind == "footnote":
            # A second `[^id]:` line would be a duplicate label, so both
            # languages live inside one definition as a continuation line.
            original = block.meta.get("text", "").strip()
            lead, echo = (target, original) if zh_first else (
                f"[^{block.meta['id']}]: {original}", _strip_label(target))
            out.append(f"{lead}\n    *{echo}*" if echo else lead)
        else:
            english = f"{marker}\n{source}" if marker else source
            out.extend([target, english] if zh_first else [english, target])
        pairs += 1

    body = "\n\n".join(x for x in out if x.strip())
    if header:
        body = f"{header.rstrip()}\n\n{body}"
    return Assembled(text=body.rstrip() + "\n", pairs=pairs, passthrough=passthrough)


def _heading_pair(block: Block, target: str, cfg: Config,
                  marker: str, zh_first: bool) -> list[str]:
    """Render a heading so that only one of the two languages enters the TOC."""
    style = cfg.layout.heading_style
    hashes = "#" * block.meta.get("level", 2)
    original = block.meta.get("text", "").strip()
    zh_text = (target.splitlines()[0] if target else "").lstrip("#").strip()

    if style == "none" or not original:
        return [f"{hashes} {zh_text or original}"]

    if style == "inline":
        pair = f"{zh_text} · {original}" if zh_first else f"{original} · {zh_text}"
        return [f"{hashes} {pair}"]

    # "italic-below": one language carries the document structure, the other
    # follows as a muted line that no table of contents will pick up.
    lead, echo = (zh_text, original) if zh_first else (original, zh_text)
    echo_line = f"*{echo}*" if PLAIN_RE.match(echo) else echo
    if marker and zh_first:
        echo_line = f"{marker}\n{echo_line}"
    return [f"{hashes} {lead}", echo_line]


def _same(a: str, b: str) -> bool:
    norm = lambda s: re.sub(r"\s+", " ", s).strip().lower()  # noqa: E731
    return norm(a) == norm(b)


def build_header(title: str, source_name: str, cfg: Config, stats: dict) -> str:
    """A small provenance block at the top of every generated document."""
    lines = [
        "<!-- Generated by hy-ebook-translator.",
        f"     source: {source_name}",
        f"     api model: {cfg.api.model or 'unspecified'}",
        *( [f"     fallback models: {', '.join(cfg.api.fallback_models)}"]
           if cfg.api.fallback_models else [] ),
        f"     direction: {cfg.translate.source_lang} → {cfg.translate.target_lang}",
        f"     segments: {stats.get('units', 0)} ({stats.get('translated', 0)} translated,"
        f" {stats.get('cached', 0)} cached, {stats.get('skipped', 0)} verbatim)",
        "     Each block appears as translation first, original second. -->",
    ]
    return "\n".join(lines)


def _strip_label(definition: str) -> str:
    return re.sub(r"^\[\^[^\]]+\]:\s*", "", definition).strip()
